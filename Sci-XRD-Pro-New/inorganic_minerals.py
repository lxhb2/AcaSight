CU_KA = 1.5406  # Cu Kα 波长 (Å)

def calculate_2theta(d_values):
    """计算 2θ 角"""
    result = []
    for d in d_values:
        try:
            if d > 0:
                sin_theta = CU_KA / (2 * d)
                if abs(sin_theta) <= 1.0:
                    theta = 2 * math.degrees(math.asin(sin_theta))
                    result.append(round(theta, 2))
                else:
                    result.append(0)
            else:
                result.append(0)
        except:
            result.append(0)
    return result

