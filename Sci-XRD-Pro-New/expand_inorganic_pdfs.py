CU_KA = 1.5406  # Cu Kα radiation

def calculate_2theta(d_values):
    """计算 2-theta 值"""
    theta_values = []
    for d in d_values:
        try:
            sin_theta = CU_KA / (2 * d)
            if abs(sin_theta) <= 1.0:
                theta = 2 * math.degrees(math.asin(sin_theta))
                theta_values.append(round(theta, 2))
            else:
                theta_values.append(0)
        except:
            theta_values.append(0)
    return theta_values

